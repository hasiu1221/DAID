class EnemyTemplate:
    def __init__(
        self,
        template_id: str,
        name: str,
        char_class: CharacterClass,
        difficulty: str,  # "Łatwy", "Średni", "Trudny", "BOSS"
        reward_gold: int,
        reward_exp: int,
        max_hp: float,
        max_stamina: float,
        max_mana: float,
        strength: float,
        agility: float,
        intelligence: float,
        defense: float,
        dodge_chance: float,
        crit_chance: float,
        skills: List[Skill],
        description: str,
    ):
        self.template_id = template_id
        self.name = name
        self.char_class = char_class
        self.difficulty = difficulty
        self.reward_gold = reward_gold
        self.reward_exp = reward_exp
        self.max_hp = max_hp
        self.max_stamina = max_stamina
        self.max_mana = max_mana
        self.strength = strength
        self.agility = agility
        self.intelligence = intelligence
        self.defense = defense
        self.dodge_chance = dodge_chance
        self.crit_chance = crit_chance
        self.skills = skills
        self.description = description

    def instantiate(self, unique_id: Optional[str] = None) -> Character:
        c_id = unique_id or f"enemy_{self.template_id}"
        copied_skills = [copy.deepcopy(s) for s in self.skills]
        return Character(
            id=c_id,
            name=self.name,
            char_class=self.char_class,
            max_hp=self.max_hp,
            current_hp=self.max_hp,
            max_stamina=self.max_stamina,
            current_stamina=self.max_stamina,
            max_mana=self.max_mana,
            current_mana=self.max_mana,
            strength=self.strength,
            agility=self.agility,
            intelligence=self.intelligence,
            defense=self.defense,
            dodge_chance=self.dodge_chance,
            crit_chance=self.crit_chance,
            skills=copied_skills,
        )


